function generateAgentFiles(agents: AgentRole[]): Array<{ path: string; content: string }> {
  return agents.map(agent => {
    const className = agent.name.replace(/\s+/g, "");
    const slug = className.toLowerCase();

    return {
      path: `src/lib/agents/${slug}.ts`,
      content: `// ============================================================
// ${agent.name} Agent
// Role: ${agent.role}
// ${agent.description}
// ============================================================

export class ${className}Agent {
  private role = "${agent.role}";

  async execute(input: string, context?: Record<string, any>): Promise<string> {
    // TODO: Implement ${agent.name} logic
    console.log(\`[${this.role}] Processing: \${input}\`);
    return \`Processed by ${agent.name}: \${input}\`;
  }

  async processWithMemory(input: string, memory: any[]): Promise<string> {
    // TODO: Add memory-augmented processing
    return this.execute(input);
  }
}

export const ${slug}Agent = new ${className}Agent();
`,
    };
  });
}

