// ============================================================
// Starter Repo Generator
// Generates complete starter codebase blueprints
// ============================================================

import { ProductBuild, BuildVariant, TechLayer, AgentRole } from "@/lib/agents/types";

export interface StarterBlueprint {
  name: string;
  description: string;
  variant: string;
  folderStructure: Record<string, any>;
  readme: string;
  dockerCompose: string;
  envExample: string;
  packageJson: Record<string, any>;
  mainConfig: string;
  agentFiles: Array<{ path: string; content: string }>;
  apiRoutes: Array<{ path: string; content: string }>;
}

/**
 * Generate a complete starter repo blueprint for a product
 */
export function generateStarterRepo(product: ProductBuild, variantTier: string = "intermediate"): StarterBlueprint {
  const variant = product.buildVariants.find(v => v.tier === variantTier) || product.buildVariants[1];
  const slug = product.title.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, "");

  return {
    name: slug,
    description: product.tagline,
    variant: variant.tier,
    folderStructure: generateFolderStructure(variant),
    readme: generateFullReadme(product, variant),
    dockerCompose: generateDockerCompose(variant),
    envExample: generateEnvExample(variant),
    packageJson: generatePackageJson(product, variant),
    mainConfig: generateMainConfig(variant),
    agentFiles: generateAgentFiles(variant.agents),
    apiRoutes: generateApiRoutes(variant),
  };
}

