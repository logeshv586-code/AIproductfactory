function generateDockerCompose(variant: BuildVariant): string {
  const hasMemory = variant.techStack?.some(t => t.layer === "Memory");
  const hasDB = variant.techStack?.some(t => t.layer === "Backend" || t.layer === "Data");

  return `version: '3.8'

services:
  app:
    build: .
    ports:
      - "3000:3000"
    environment:
      - NODE_ENV=development
      - DATABASE_URL=file:./dev.db
    volumes:
      - .:/app
      - /app/node_modules
    depends_on:
     ${hasMemory ? `- chroma` : ''}

${hasMemory ? `  chroma:
    image: chromadb/chroma:latest
    ports:
      - "8000:8000"
    volumes:
      - chroma_data:/chroma/chroma
    environment:
      - ANONYMIZED_TELEMETRY=FALSE

` : ''}${hasDB ? `  postgres:
    image: postgres:16-alpine
    ports:
      - "5432:5432"
    environment:
      POSTGRES_DB: aidev
      POSTGRES_USER: dev
      POSTGRES_PASSWORD: devpassword
    volumes:
      - pg_data:/var/lib/postgresql/data

` : ''}volumes:
${hasMemory ? `  chroma_data:` : ''}${hasDB ? `\n  pg_data:` : ''}
`;
}

